const LANG_KEY = "aldrich-lang";
const SUPPORTED = ["en","zh-CN","zh-TW","fr"];
const HTML_LANG_MAP = {"en":"en","zh-CN":"zh-CN","zh-TW":"zh-TW","fr":"fr"};

function detectInitialLang() {
  // Always default to English on first visit. User toggles 简 / 繁 / FR if
  // they want; the choice persists in localStorage from then on.
  let stored;
  try { stored = localStorage.getItem(LANG_KEY); } catch {}
  if (stored && SUPPORTED.includes(stored)) return stored;
  return "en";
}

function setLang(lang) {
  if (!SUPPORTED.includes(lang)) lang = "en";
  try { localStorage.setItem(LANG_KEY, lang); } catch {}
  document.documentElement.lang = HTML_LANG_MAP[lang];

  document.querySelectorAll("[data-i18n]").forEach(el => {
    const key = el.dataset.i18n;
    const t = T[key] && T[key][lang];
    if (t === undefined) return;
    if (key === "lede") {
      const sentenceEnd = t.search(/[。.!?]/);
      el.innerHTML = sentenceEnd < 0 ? t : `<span class="invitation-main">${t.slice(0,sentenceEnd + 1)}</span><span class="invitation-tail">${t.slice(sentenceEnd + 1)}</span>`;
    }
    else if (key === "credo") {
      const separator = t.indexOf(lang.startsWith("zh") ? "，" : ",");
      if(separator < 0) { el.textContent = t; return; }
      const head = document.createElement("span");
      const tail = document.createElement("span");
      head.className = "credo-head";
      tail.className = "credo-tail";
      head.textContent = t.slice(0,separator + 1);
      tail.textContent = t.slice(separator + 1);
      el.replaceChildren(head,tail);
    }
    else if (el.hasAttribute("data-i18n-html")) el.innerHTML = t;
    else el.textContent = t;
  });

  document.querySelectorAll("#langToggle button").forEach(b => {
    const active = b.dataset.lang === lang;
    b.classList.toggle("active", active);
    b.setAttribute("aria-pressed", String(active));
  });

  // The live edition strip is locale-aware too
  updateLiveStrip();
}

// ─── Live edition strip (auto-incrementing No. + Beijing date / time) ───
const FYI_EPOCH = new Date("2026-04-27T00:00:00+08:00"); // launch midnight 北京
const LOCALE_MAP = {"en":"en-US","zh-CN":"zh-CN","zh-TW":"zh-TW","fr":"fr-FR"};
const VOL_LABEL = {
  "en":    n => `VOL. I · NO. ${n}`,
  "zh-CN": n => `卷一 · 第 ${n} 期`,
  "zh-TW": n => `卷一 · 第 ${n} 期`,
  "fr":    n => `VOL. I · N° ${n}`,
};
function editionNumber() {
  return Math.max(1, Math.floor((Date.now() - FYI_EPOCH.getTime()) / 86400000) + 1);
}
function updateLiveStrip() {
  const el = document.getElementById("stripRight");
  if (!el) return;
  const lang = document.documentElement.lang || "en";
  const locale = LOCALE_MAP[lang] || "en-US";
  const tz = "Asia/Shanghai";
  const now = new Date();
  const day = new Intl.DateTimeFormat(locale, {weekday:"short", timeZone:tz}).format(now);
  const md  = new Intl.DateTimeFormat(locale, {month:"short", day:"numeric", timeZone:tz}).format(now);
  const t   = new Intl.DateTimeFormat("en-US", {hour:"2-digit", minute:"2-digit", hour12:false, timeZone:tz}).format(now);
  const vol = (VOL_LABEL[lang] || VOL_LABEL.en)(editionNumber());
  el.textContent = `${vol} · ${day.toUpperCase()} · ${md.toUpperCase()} · ${t} PEK`;
}
setInterval(updateLiveStrip, 60_000);  // tick every minute

